export function renderDocs(el) {
  el.innerHTML = `
    <p class="doc-lead">
      按模块列出各功能的作用与操作。分组管理、审计、令牌等页面的具体字段，以对应页面内说明为准。
    </p>
    ${SECTIONS.map(
      (s) => `
      <div class="doc-section">
        <div class="doc-title">${s.title}</div>
        <p class="doc-desc">${s.desc}</p>
        <div class="doc-list">
          ${s.items
            .map(
              ([name, effect, how]) => `
            <div class="doc-item">
              <div class="doc-item-name">${name}</div>
              <div class="doc-item-text">
                <div><b>作用</b>：${effect}</div>
                <div><b>操作</b>：${how}</div>
              </div>
            </div>`
            )
            .join('')}
        </div>
      </div>`
    ).join('')}`;
}
